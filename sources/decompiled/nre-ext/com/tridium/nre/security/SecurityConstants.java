   public static final boolean canCheckTpk() {
      return TPK.length != 0;
   }

   public static void checkTpk(String className, X509Certificate cert) throws SecurityException {
      PublicKey pub = cert.getPublicKey();
      X509EncodedKeySpec spec = new X509EncodedKeySpec(pub.getEncoded());
      byte[] pubBytes = spec.getEncoded();
      if (!Arrays.equals(TPK, pubBytes)) {
         throw new SecurityException(className + " violates integrity check");
      }
   }

   public static byte[] getTpk() {
      return (byte[])TPK.clone();
   }

   private static void dumpBytes(byte[] pubBytes) {
      System.out.print("  {");

      for (int i = 0; i < pubBytes.length; i++) {
         if (i % 16 == 0) {
            System.out.print("\n    ");
         }

         System.out.print("(byte) 0x" + Integer.toString((pubBytes[i] & 255) + 256, 16).substring(1) + ", ");
      }

      System.out.println("\n  };");
   }
